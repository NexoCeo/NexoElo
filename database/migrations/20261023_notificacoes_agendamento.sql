-- Executar antes de publicar a API que gera notificações de agendamento.
CREATE TABLE IF NOT EXISTS NOTIFICACOES_AGENDAMENTO (
 ID BIGSERIAL PRIMARY KEY,
 AGENDAMENTO_ID INTEGER NOT NULL,
 DESTINATARIO_USUARIO_ID INTEGER NOT NULL,
 TITULO VARCHAR(100) NOT NULL,
 MENSAGEM TEXT NOT NULL,
 DATA_AGENDAMENTO TIMESTAMP NOT NULL,
 LIDA BOOLEAN NOT NULL DEFAULT FALSE,
 CRIADA_EM TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 CONSTRAINT UX_NOTIF_AGENDAMENTO_DEST UNIQUE(AGENDAMENTO_ID, DESTINATARIO_USUARIO_ID)
);
CREATE INDEX IF NOT EXISTS IX_NOTIF_AGENDAMENTO_DEST
 ON NOTIFICACOES_AGENDAMENTO(DESTINATARIO_USUARIO_ID, CRIADA_EM DESC);
