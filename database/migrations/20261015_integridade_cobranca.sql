-- Aplicar antes do deploy das protecoes de checkout (PostgreSQL Render).
CREATE TABLE IF NOT EXISTS ASSINATURA_CHECKOUT_LOCK (
 USUARIO_FK INTEGER PRIMARY KEY REFERENCES USUARIOS(ID_USUARIO) ON DELETE CASCADE,
 EXPIRA_EM TIMESTAMPTZ NOT NULL,
 STRIPE_SESSION_ID TEXT NULL
);
CREATE TABLE IF NOT EXISTS STRIPE_WEBHOOK_PROCESSADOS (
 EVENT_ID TEXT PRIMARY KEY,
 PROCESSADO_EM TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS UX_ASSINATURAS_STRIPE_SUBSCRIPTION
 ON ASSINATURAS(STRIPE_SUBSCRIPTION_ID) WHERE STRIPE_SUBSCRIPTION_ID IS NOT NULL;
