-- Um agendamento continua sendo uma única reserva e pode incluir múltiplos serviços.
CREATE TABLE IF NOT EXISTS AGENDAMENTO_SERVICOS (
    AGENDAMENTO_FK INTEGER NOT NULL REFERENCES AGENDAMENTOS(ID_AGENDAMENTO) ON DELETE CASCADE,
    SERVICO_FK INTEGER NOT NULL REFERENCES SERVICOS(ID_SERVICO),
    PRIMARY KEY (AGENDAMENTO_FK, SERVICO_FK)
);
CREATE INDEX IF NOT EXISTS IDX_AGENDAMENTO_SERVICOS_SERVICO ON AGENDAMENTO_SERVICOS(SERVICO_FK);
