-- Pagamentos de serviços são independentes de assinaturas.
-- Executar manualmente no Neon antes do deploy da API.
CREATE TABLE IF NOT EXISTS CONFIGURACOES_PAGAMENTO (
  USUARIO_FK INTEGER PRIMARY KEY REFERENCES USUARIOS(ID_USUARIO),
  MODALIDADE VARCHAR(12) NOT NULL DEFAULT 'PRESENCIAL'
    CHECK (MODALIDADE IN ('PRESENCIAL','ONLINE','AMBOS')),
  STRIPE_CONNECTED_ACCOUNT_ID VARCHAR(100),
  ATUALIZADO_EM TIMESTAMP NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS UX_CONFIG_PAG_STRIPE_ACCOUNT
  ON CONFIGURACOES_PAGAMENTO(STRIPE_CONNECTED_ACCOUNT_ID)
  WHERE STRIPE_CONNECTED_ACCOUNT_ID IS NOT NULL;

CREATE TABLE IF NOT EXISTS PAGAMENTOS_AGENDAMENTO (
  ID_PAGAMENTO BIGSERIAL PRIMARY KEY,
  AGENDAMENTO_FK INTEGER NOT NULL REFERENCES AGENDAMENTOS(ID_AGENDAMENTO),
  RECEBEDOR_USUARIO_FK INTEGER NOT NULL REFERENCES USUARIOS(ID_USUARIO),
  CLIENTE_USUARIO_FK INTEGER NOT NULL REFERENCES USUARIOS(ID_USUARIO),
  VALOR_CENTAVOS BIGINT NOT NULL CHECK(VALOR_CENTAVOS > 0),
  METODO VARCHAR(12) NOT NULL CHECK(METODO IN ('PRESENCIAL','ONLINE')),
  STATUS VARCHAR(20) NOT NULL CHECK(STATUS IN ('PENDENTE','PAGO','FALHOU','REEMBOLSADO')),
  STRIPE_SESSION_ID VARCHAR(255),
  TENTATIVA INTEGER NOT NULL DEFAULT 0,
  STRIPE_PAYMENT_INTENT_ID VARCHAR(255),
  CRIADO_EM TIMESTAMP NOT NULL DEFAULT NOW(),
  ATUALIZADO_EM TIMESTAMP NOT NULL DEFAULT NOW(),
  UNIQUE(AGENDAMENTO_FK)
);
CREATE UNIQUE INDEX IF NOT EXISTS UX_PAG_AGEN_SESSION
 ON PAGAMENTOS_AGENDAMENTO(STRIPE_SESSION_ID) WHERE STRIPE_SESSION_ID IS NOT NULL;
CREATE INDEX IF NOT EXISTS IX_PAG_AGEN_RECEBEDOR ON PAGAMENTOS_AGENDAMENTO(RECEBEDOR_USUARIO_FK);

CREATE TABLE IF NOT EXISTS PAGAMENTOS_AGENDAMENTO_WEBHOOKS (
 EVENT_ID VARCHAR(255) PRIMARY KEY,
 PROCESSADO_EM TIMESTAMP NOT NULL DEFAULT NOW()
);
