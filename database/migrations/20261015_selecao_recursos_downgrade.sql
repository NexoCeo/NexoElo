-- Executar no PostgreSQL do NexoElo antes de usar a selecao de downgrade.
-- Registros nao selecionados permanecem no banco e no historico.
CREATE TABLE IF NOT EXISTS ASSINATURA_RECURSOS_ATIVOS (
    USUARIO_FK INTEGER NOT NULL REFERENCES USUARIOS(ID_USUARIO) ON DELETE CASCADE,
    TIPO_RECURSO VARCHAR(20) NOT NULL CHECK (TIPO_RECURSO IN ('SERVICO','PROFISSIONAL')),
    RECURSO_ID INTEGER NOT NULL,
    PRIMARY KEY (USUARIO_FK,TIPO_RECURSO,RECURSO_ID)
);
CREATE INDEX IF NOT EXISTS IDX_ASSINATURA_RECURSOS_USUARIO
    ON ASSINATURA_RECURSOS_ATIVOS (USUARIO_FK,TIPO_RECURSO);
