ALTER TABLE PRESTADOR_CONFIG
    ADD COLUMN IF NOT EXISTS HORA_INICIO TIME DEFAULT TIME '08:00',
    ADD COLUMN IF NOT EXISTS HORA_FIM TIME DEFAULT TIME '18:00',
    ADD COLUMN IF NOT EXISTS DIAS_FUNCIONAMENTO VARCHAR(100) DEFAULT 'SEGUNDA,TERCA,QUARTA,QUINTA,SEXTA';

UPDATE PRESTADOR_CONFIG
SET HORA_INICIO = COALESCE(HORA_INICIO, TIME '08:00'),
    HORA_FIM = COALESCE(HORA_FIM, TIME '18:00'),
    DIAS_FUNCIONAMENTO = COALESCE(NULLIF(TRIM(DIAS_FUNCIONAMENTO), ''), 'SEGUNDA,TERCA,QUARTA,QUINTA,SEXTA'),
    LIMITE_DIARIO = COALESCE(NULLIF(LIMITE_DIARIO, 0), 1),
    LIMITE_SEMANAL = COALESCE(NULLIF(LIMITE_SEMANAL, 0), 1);

CREATE TABLE IF NOT EXISTS FUNCIONAMENTO_INTERVALOS (
    ID_FUNCIONAMENTO_INTERVALO INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USUARIO_FK INTEGER NOT NULL,
    DIA_FUNCIONAMENTO VARCHAR(20) CHECK (
        DIA_FUNCIONAMENTO IN (
            'DOMINGO',
            'SEGUNDA',
            'TERCA',
            'QUARTA',
            'QUINTA',
            'SEXTA',
            'SABADO'
        )
    ) NOT NULL,
    HORA_INICIO TIME NOT NULL,
    HORA_FIM TIME NOT NULL,
    FOREIGN KEY (USUARIO_FK) REFERENCES USUARIOS (ID_USUARIO),
    CONSTRAINT CK_FUNCIONAMENTO_INTERVALOS_HORARIO CHECK (HORA_INICIO < HORA_FIM)
);

INSERT INTO FUNCIONAMENTO_INTERVALOS (
    USUARIO_FK,
    DIA_FUNCIONAMENTO,
    HORA_INICIO,
    HORA_FIM
)
SELECT
    PC.USUARIO_FK,
    TRIM(DIA) AS DIA_FUNCIONAMENTO,
    COALESCE(PC.HORA_INICIO, TIME '08:00') AS HORA_INICIO,
    COALESCE(PC.HORA_FIM, TIME '18:00') AS HORA_FIM
FROM PRESTADOR_CONFIG PC
CROSS JOIN LATERAL regexp_split_to_table(
    COALESCE(NULLIF(TRIM(PC.DIAS_FUNCIONAMENTO), ''), 'SEGUNDA,TERCA,QUARTA,QUINTA,SEXTA'),
    ','
) AS DIA
WHERE NOT EXISTS (
    SELECT 1
    FROM FUNCIONAMENTO_INTERVALOS FI
    WHERE FI.USUARIO_FK = PC.USUARIO_FK
);

