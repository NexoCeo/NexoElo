            'ATIVA',
            'NAO_ATIVA',
            'EXPIRADO',
            'CANCELADA',
            'PENDENTE',
            'CANCELAMENTO_PENDENTE'
        )
    );

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conrelid = 'assinaturas'::regclass
          AND conname = 'fk_assinaturas_usuarios'
    ) THEN
        ALTER TABLE ASSINATURAS
