CREATE TABLE IF NOT EXISTS ASSINATURAS (
    ID_ASSINATURA INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USUARIO_FK INTEGER NOT NULL,
    STATUS_ASSINATURA VARCHAR(25) DEFAULT 'NAO_ATIVA' CHECK (
        STATUS_ASSINATURA IN (
            'ATIVA',
            'NAO_ATIVA',
            'EXPIRADO',
            'CANCELADA',
            'PENDENTE',
            'CANCELAMENTO_PENDENTE'
        )
    ) NOT NULL,
    DATA_INICIO_ASSINATURA TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    DATA_FIM_ASSINATURA TIMESTAMP,
    STRIPE_CUSTOMER_ID VARCHAR(255),
    STRIPE_SUBSCRIPTION_ID VARCHAR(255),
    STRIPE_PRICE_ID VARCHAR(255),
    DATA_CRIACAO_ASSINATURA TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    DATA_ALTERACAO_ASSINATURA TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (USUARIO_FK) REFERENCES USUARIOS (ID_USUARIO)
);

ALTER TABLE ASSINATURAS
    ADD COLUMN IF NOT EXISTS ID_ASSINATURA INTEGER GENERATED BY DEFAULT AS IDENTITY,
    ADD COLUMN IF NOT EXISTS USUARIO_FK INTEGER,
    ADD COLUMN IF NOT EXISTS STATUS_ASSINATURA VARCHAR(25) DEFAULT 'NAO_ATIVA',
    ADD COLUMN IF NOT EXISTS DATA_INICIO_ASSINATURA TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    ADD COLUMN IF NOT EXISTS DATA_FIM_ASSINATURA TIMESTAMP,
    ADD COLUMN IF NOT EXISTS STRIPE_CUSTOMER_ID VARCHAR(255),
    ADD COLUMN IF NOT EXISTS STRIPE_SUBSCRIPTION_ID VARCHAR(255),
    ADD COLUMN IF NOT EXISTS STRIPE_PRICE_ID VARCHAR(255),
    ADD COLUMN IF NOT EXISTS DATA_CRIACAO_ASSINATURA TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    ADD COLUMN IF NOT EXISTS DATA_ALTERACAO_ASSINATURA TIMESTAMP DEFAULT CURRENT_TIMESTAMP;

DO $$
DECLARE
    constraint_record RECORD;
BEGIN
    FOR constraint_record IN
        SELECT conname
        FROM pg_constraint
        WHERE conrelid = 'assinaturas'::regclass
          AND contype = 'c'
          AND pg_get_constraintdef(oid) ILIKE '%STATUS_ASSINATURA%'
    LOOP
        EXECUTE format('ALTER TABLE ASSINATURAS DROP CONSTRAINT %I', constraint_record.conname);
    END LOOP;
END $$;

ALTER TABLE ASSINATURAS
    ADD CONSTRAINT CK_ASSINATURAS_STATUS
    CHECK (
