            FOREIGN KEY (USUARIO_FK) REFERENCES USUARIOS (ID_USUARIO);
    END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS UX_ASSINATURAS_USUARIO_FK
    ON ASSINATURAS (USUARIO_FK);

CREATE INDEX IF NOT EXISTS IX_ASSINATURAS_STRIPE_CUSTOMER_ID
    ON ASSINATURAS (STRIPE_CUSTOMER_ID);

CREATE UNIQUE INDEX IF NOT EXISTS UX_ASSINATURAS_STRIPE_SUBSCRIPTION_ID
    ON ASSINATURAS (STRIPE_SUBSCRIPTION_ID)
    WHERE STRIPE_SUBSCRIPTION_ID IS NOT NULL;

DO $$
DECLARE
    has_status BOOLEAN;
    has_data_fim BOOLEAN;
    has_customer BOOLEAN;
    has_subscription BOOLEAN;
    has_price BOOLEAN;
    status_expr TEXT := '''NAO_ATIVA''';
    data_fim_expr TEXT := 'NULL::TIMESTAMP';
    customer_expr TEXT := 'NULL::VARCHAR';
    subscription_expr TEXT := 'NULL::VARCHAR';
    price_expr TEXT := 'NULL::VARCHAR';
BEGIN
    SELECT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'usuarios' AND column_name = 'assinatura_ativa'
    ) INTO has_status;

    SELECT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'usuarios' AND column_name = 'data_fim_assinatura'
    ) INTO has_data_fim;

    SELECT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'usuarios' AND column_name = 'stripe_customer_id'
    ) INTO has_customer;

    SELECT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'usuarios' AND column_name = 'stripe_subscription_id'
    ) INTO has_subscription;

    SELECT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'usuarios' AND column_name = 'stripe_price_id'
    ) INTO has_price;

    IF has_status THEN
        status_expr := 'CASE WHEN U.ASSINATURA_ATIVA IN (''ATIVA'', ''NAO_ATIVA'', ''EXPIRADO'', ''CANCELADA'', ''PENDENTE'', ''CANCELAMENTO_PENDENTE'') THEN U.ASSINATURA_ATIVA ELSE ''NAO_ATIVA'' END';
    END IF;

    IF has_data_fim THEN
        data_fim_expr := 'U.DATA_FIM_ASSINATURA::TIMESTAMP';
    END IF;

    IF has_customer THEN
        customer_expr := 'U.STRIPE_CUSTOMER_ID';
    END IF;

    IF has_subscription THEN
        subscription_expr := 'U.STRIPE_SUBSCRIPTION_ID';
    END IF;

    IF has_price THEN
        price_expr := 'U.STRIPE_PRICE_ID';
    END IF;

    EXECUTE format($migrate$
            INSERT INTO ASSINATURAS (
                USUARIO_FK,
                STATUS_ASSINATURA,
                DATA_FIM_ASSINATURA,
                STRIPE_CUSTOMER_ID,
                STRIPE_SUBSCRIPTION_ID,
                STRIPE_PRICE_ID
            )
            SELECT
                U.ID_USUARIO,
                %s,
                %s,
                %s,
                %s,
                %s
            FROM USUARIOS U
            ON CONFLICT (USUARIO_FK)
            DO UPDATE SET
                STATUS_ASSINATURA = EXCLUDED.STATUS_ASSINATURA,
                DATA_FIM_ASSINATURA = COALESCE(EXCLUDED.DATA_FIM_ASSINATURA, ASSINATURAS.DATA_FIM_ASSINATURA),
                STRIPE_CUSTOMER_ID = COALESCE(EXCLUDED.STRIPE_CUSTOMER_ID, ASSINATURAS.STRIPE_CUSTOMER_ID),
                STRIPE_SUBSCRIPTION_ID = COALESCE(EXCLUDED.STRIPE_SUBSCRIPTION_ID, ASSINATURAS.STRIPE_SUBSCRIPTION_ID),
                STRIPE_PRICE_ID = COALESCE(EXCLUDED.STRIPE_PRICE_ID, ASSINATURAS.STRIPE_PRICE_ID),
                DATA_ALTERACAO_ASSINATURA = CURRENT_TIMESTAMP
        $migrate$,
        status_expr,
        data_fim_expr,
        customer_expr,
        subscription_expr,
        price_expr);
END $$;

