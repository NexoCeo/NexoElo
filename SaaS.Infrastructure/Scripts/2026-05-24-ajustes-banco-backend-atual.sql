CREATE TABLE IF NOT EXISTS PAISES (
    ID_PAIS INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME_PAIS VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS ESTADOS (
    ID_ESTADO INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME_ESTADO VARCHAR(100) NOT NULL,
    PAIS_FK INTEGER NOT NULL,
    FOREIGN KEY (PAIS_FK) REFERENCES PAISES (ID_PAIS),
    UNIQUE (NOME_ESTADO, PAIS_FK)
);

CREATE TABLE IF NOT EXISTS CIDADES (
    ID_CIDADE INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME_CIDADE VARCHAR(100) NOT NULL,
    ESTADO_FK INTEGER NOT NULL,
    FOREIGN KEY (ESTADO_FK) REFERENCES ESTADOS (ID_ESTADO),
    UNIQUE (NOME_CIDADE, ESTADO_FK)
);

CREATE TABLE IF NOT EXISTS USUARIOS (
    ID_USUARIO INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME_USUARIO VARCHAR(100) NOT NULL,
    EMAIL_USUARIO VARCHAR(100) UNIQUE,
    TELEFONE_USUARIO VARCHAR(20),
    SLUG_USUARIO VARCHAR(100),
    SENHA_USUARIO VARCHAR(255) NOT NULL,
    FOTO_PERFIL VARCHAR(255) NOT NULL,
    TIPO_USUARIO VARCHAR(20) CHECK (TIPO_USUARIO IN ('CLIENTE', 'PROFISSIONAL', 'AUTONOMO', 'EMPRESA')) NOT NULL,
    DATA_CRIACAO_USUARIO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    DATA_ALTERACAO_USUARIO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CIDADE_FK INTEGER NOT NULL,
    FOREIGN KEY (CIDADE_FK) REFERENCES CIDADES (ID_CIDADE),
    CONSTRAINT CK_USUARIOS_CONTATO_LOGIN CHECK (
        (
            TIPO_USUARIO = 'CLIENTE'
            AND (
                NULLIF(TRIM(COALESCE(EMAIL_USUARIO, '')), '') IS NOT NULL
                OR NULLIF(TRIM(COALESCE(TELEFONE_USUARIO, '')), '') IS NOT NULL
            )
        )
        OR
        (
            TIPO_USUARIO <> 'CLIENTE'
            AND NULLIF(TRIM(COALESCE(EMAIL_USUARIO, '')), '') IS NOT NULL
        )
    ),
    CONSTRAINT CK_USUARIOS_SLUG_PAPEL CHECK (
        SLUG_USUARIO IS NULL OR TIPO_USUARIO IN ('EMPRESA', 'AUTONOMO')
    )
);

