BEGIN;

CREATE TABLE IF NOT EXISTS PROFISSIONAL_SERVICOS (
    ID_PROFISSIONAL_SERVICO INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PROFISSIONAL_FK INTEGER NOT NULL,
    EMPRESA_FK INTEGER NOT NULL,
    SERVICO_FK INTEGER NOT NULL,
    DATA_VINCULO TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_PROFISSIONAL_SERVICOS_PROFISSIONAL
        FOREIGN KEY (PROFISSIONAL_FK) REFERENCES USUARIOS (ID_USUARIO) ON DELETE CASCADE,
    CONSTRAINT FK_PROFISSIONAL_SERVICOS_EMPRESA
        FOREIGN KEY (EMPRESA_FK) REFERENCES USUARIOS (ID_USUARIO) ON DELETE CASCADE,
    CONSTRAINT FK_PROFISSIONAL_SERVICOS_SERVICO
        FOREIGN KEY (SERVICO_FK) REFERENCES SERVICOS (ID_SERVICO) ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS UX_PROFISSIONAL_SERVICOS_VINCULO
    ON PROFISSIONAL_SERVICOS (PROFISSIONAL_FK, EMPRESA_FK, SERVICO_FK);

CREATE INDEX IF NOT EXISTS IX_PROFISSIONAL_SERVICOS_PROFISSIONAL_EMPRESA
    ON PROFISSIONAL_SERVICOS (PROFISSIONAL_FK, EMPRESA_FK);

CREATE INDEX IF NOT EXISTS IX_PROFISSIONAL_SERVICOS_SERVICO_FK
    ON PROFISSIONAL_SERVICOS (SERVICO_FK);

-- Mantem o comportamento atual para profissionais ja aprovados. A empresa
-- podera remover os servicos que cada profissional nao oferece pela interface.
WITH ULTIMO_VINCULO AS (
    SELECT DISTINCT ON (PROFISSIONAL_FK, EMPRESA_FK)
        PROFISSIONAL_FK,
        EMPRESA_FK,
        STATUS_SOLICITACAO
    FROM VINCULOS
    ORDER BY
        PROFISSIONAL_FK,
        EMPRESA_FK,
        DATA_SOLICITACAO DESC,
        ID_SOLICITACAO DESC
)
INSERT INTO PROFISSIONAL_SERVICOS (
    PROFISSIONAL_FK,
    EMPRESA_FK,
    SERVICO_FK
)
SELECT
    V.PROFISSIONAL_FK,
    V.EMPRESA_FK,
    S.ID_SERVICO
FROM ULTIMO_VINCULO V
INNER JOIN USUARIOS P
        ON P.ID_USUARIO = V.PROFISSIONAL_FK
       AND P.TIPO_USUARIO = 'PROFISSIONAL'
INNER JOIN USUARIOS E
        ON E.ID_USUARIO = V.EMPRESA_FK
       AND E.TIPO_USUARIO = 'EMPRESA'
INNER JOIN SERVICOS S
        ON S.USUARIO_FK = V.EMPRESA_FK
WHERE V.STATUS_SOLICITACAO = 'APROVADO'
ON CONFLICT (PROFISSIONAL_FK, EMPRESA_FK, SERVICO_FK) DO NOTHING;

COMMIT;
